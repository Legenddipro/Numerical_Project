@pytest.mark.skip(reason="not yet implemented")
def test_gate_g3_rhs_identity_holds_for_fsal_variants():
    """Gate G3, the strongest check available.

    For baseline, fsalr, and rfsal, within each individual run::

        nf == c0 + (s-1) * (n_accept + n_reject)

    Every attempt costs s-1 evaluations, rejections included, because stage 1
    is always served from the FSAL cache and a rejected step restarts from the
    same u_n. Integers admit no "close enough", so passing this is strong
    evidence the FSAL bookkeeping is right -- the single hardest thing to get
    correct in this project.

    Note this is a within-run identity, NOT a cross-run comparison. The three
    methods need not report equal totals: relaxation shifts both the state and
    the time, so they follow different trajectories and their controllers make
    different accept/reject decisions. Asserting equal totals would fail a
    correct implementation.
    """


