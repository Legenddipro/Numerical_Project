@pytest.mark.skip(reason="not yet implemented")
def test_gate_g5_matches_julia_reference():
    """Gate G5. Against a stored table generated by the authors' Julia code on
    the same fixed initial condition (omega=1.5, theta=1.0 over t in [0, 10]):
    RHS counts must match exactly, errors to several digits.

    The reference table is produced by whoever runs the Julia side and checked
    into the repo as data; this test only reads it.

    Pin the startup constant c0 to the authors' convention first. Their
    ``ode_determine_initdt`` performs two RHS evaluations that are *not* added
    to nf when dt is auto-selected, while the single evaluation *is* counted
    when dt is supplied. Mismatching that convention fails this gate as an
    off-by-two which looks exactly like a real bug.

    Must pass before any Monte Carlo sweep is launched. Debugging a wrong port
    after generating a thousand samples of bad data is the failure mode this
    gate exists to prevent.
    """


